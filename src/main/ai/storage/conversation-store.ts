// Conversation History Store
// Per-NPC, per-player message persistence with compression and pagination

import type Database from 'better-sqlite3';
import type { ConversationMessage } from '../types/ai';

export class ConversationStore {
  private db: Database.Database;
  private maxHistoryMessages: number = 50;

  constructor(db: Database.Database, maxHistoryMessages: number = 50) {
    this.db = db;
    this.maxHistoryMessages = maxHistoryMessages;
  }

  /**
   * Add a message to conversation history
   */
  addMessage(
    npcId: string,
    playerId: string,
    role: 'user' | 'assistant',
    content: string,
    tokensUsed: number = 0,
    model: string = 'claude-haiku-4-5-20251001'
  ): ConversationMessage {
    const now = new Date();

    const stmt = this.db.prepare(`
      INSERT INTO conversation_history (npc_id, player_id, message_role, message_content, tokens_used, model_used, created_at)
      VALUES (?, ?, ?, ?, ?, ?, ?)
    `);

    stmt.run(npcId, playerId, role, content, tokensUsed, model, now.toISOString());

    // Update metadata
    this.updateMetadata(npcId, playerId);

    return {
      id: '', // Will be generated by DB
      npcId,
      playerId,
      role,
      content,
      tokensUsed,
      model: model as any,
      createdAt: now,
    };
  }

  /**
   * Get recent conversation history for context
   */
  getRecentHistory(npcId: string, playerId: string, limit: number = 20): ConversationMessage[] {
    const stmt = this.db.prepare(`
      SELECT id, npc_id, player_id, message_role, message_content, tokens_used, model_used, created_at
      FROM conversation_history
      WHERE npc_id = ? AND player_id = ? AND is_archived = 0
      ORDER BY created_at DESC
      LIMIT ?
    `);

    const rows: any[] = stmt.all(npcId, playerId, limit);

    return rows
      .reverse() // Return in chronological order
      .map((row) => ({
        id: row.id,
        npcId: row.npc_id,
        playerId: row.player_id,
        role: row.message_role as 'user' | 'assistant',
        content: row.message_content,
        tokensUsed: row.tokens_used,
        model: row.model_used as any,
        createdAt: new Date(row.created_at),
      }));
  }

  /**
   * Get full conversation history (paginated)
   */
  getFullHistory(npcId: string, playerId: string, page: number = 0, pageSize: number = 100): {
    messages: ConversationMessage[];
    total: number;
    page: number;
    pageSize: number;
  } {
    const offset = page * pageSize;

    const countStmt = this.db.prepare(`
      SELECT COUNT(*) as count FROM conversation_history
      WHERE npc_id = ? AND player_id = ? AND is_archived = 0
    `);
    const countRow: any = countStmt.get(npcId, playerId);

    const stmt = this.db.prepare(`
      SELECT id, npc_id, player_id, message_role, message_content, tokens_used, model_used, created_at
      FROM conversation_history
      WHERE npc_id = ? AND player_id = ? AND is_archived = 0
      ORDER BY created_at ASC
      LIMIT ? OFFSET ?
    `);

    const rows: any[] = stmt.all(npcId, playerId, pageSize, offset);

    return {
      messages: rows.map((row) => ({
        id: row.id,
        npcId: row.npc_id,
        playerId: row.player_id,
        role: row.message_role as 'user' | 'assistant',
        content: row.message_content,
        tokensUsed: row.tokens_used,
        model: row.model_used as any,
        createdAt: new Date(row.created_at),
      })),
      total: countRow?.count || 0,
      page,
      pageSize,
    };
  }

  /**
   * Clear old messages (archive when exceeding limit)
   */
  pruneHistory(npcId: string, playerId: string): number {
    const countStmt = this.db.prepare(`
      SELECT COUNT(*) as count FROM conversation_history
      WHERE npc_id = ? AND player_id = ? AND is_archived = 0
    `);
    const countRow: any = countStmt.get(npcId, playerId);
    const totalMessages = countRow?.count || 0;

    if (totalMessages <= this.maxHistoryMessages) {
      return 0;
    }

    const excessMessages = totalMessages - this.maxHistoryMessages;

    const archiveStmt = this.db.prepare(`
      UPDATE conversation_history
      SET is_archived = 1
      WHERE npc_id = ? AND player_id = ? AND is_archived = 0
      ORDER BY created_at ASC
      LIMIT ?
    `);

    const result = archiveStmt.run(npcId, playerId, excessMessages);
    return (result.changes as number) || 0;
  }

  /**
   * Delete all messages older than specified days
   */
  deleteOldMessages(daysToKeep: number = 90): number {
    const cutoffDate = new Date();
    cutoffDate.setDate(cutoffDate.getDate() - daysToKeep);

    const stmt = this.db.prepare(`
      DELETE FROM conversation_history
      WHERE created_at < ?
    `);

    const result = stmt.run(cutoffDate.toISOString());
    return (result.changes as number) || 0;
  }

  /**
   * Get conversation metadata
   */
  getMetadata(npcId: string, playerId: string): {
    messageCount: number;
    lastInteraction: Date | null;
    relationshipStatus: string;
  } {
    const stmt = this.db.prepare(`
      SELECT message_count, last_interaction, relationship_status
      FROM conversation_metadata
      WHERE npc_id = ? AND player_id = ?
    `);

    const row: any = stmt.get(npcId, playerId);

    if (!row) {
      return {
        messageCount: 0,
        lastInteraction: null,
        relationshipStatus: 'neutral',
      };
    }

    return {
      messageCount: row.message_count,
      lastInteraction: row.last_interaction ? new Date(row.last_interaction) : null,
      relationshipStatus: row.relationship_status,
    };
  }

  /**
   * Update relationship status for context
   */
  updateRelationshipStatus(npcId: string, playerId: string, status: string): void {
    const stmt = this.db.prepare(`
      UPDATE conversation_metadata
      SET relationship_status = ?
      WHERE npc_id = ? AND player_id = ?
    `);

    stmt.run(status, npcId, playerId);
  }

  /**
   * Private: Update conversation metadata
   */
  private updateMetadata(npcId: string, playerId: string): void {
    const stmt = this.db.prepare(`
      INSERT INTO conversation_metadata (npc_id, player_id, message_count, last_interaction)
      VALUES (?, ?, 1, ?)
      ON CONFLICT(npc_id, player_id) DO UPDATE SET
        message_count = message_count + 1,
        last_interaction = ?
    `);

    const now = new Date().toISOString();
    stmt.run(npcId, playerId, now, now);

    // Auto-prune if needed
    this.pruneHistory(npcId, playerId);
  }
}

export default ConversationStore;
